BEGIN;

-- NULL means a historical lot whose current balance cannot be reconstructed
-- safely. New receipts are tracked from this migration onward.
ALTER TABLE public.stock_batches
  ADD COLUMN IF NOT EXISTS quantity_remaining INTEGER;
ALTER TABLE public.stock_batches
  ADD COLUMN IF NOT EXISTS quantity_destroyed INTEGER NOT NULL DEFAULT 0;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.stock_batches'::REGCLASS
      AND conname = 'stock_batches_remaining_balance_check'
  ) THEN
    ALTER TABLE public.stock_batches
      ADD CONSTRAINT stock_batches_remaining_balance_check
      CHECK (
        (quantity_remaining IS NULL OR (quantity_remaining >= 0 AND quantity_remaining <= quantity_received))
        AND quantity_destroyed >= 0
        AND (quantity_remaining IS NOT NULL OR quantity_destroyed = 0)
      );
  END IF;

  ALTER TABLE public.stock_batches DROP CONSTRAINT IF EXISTS stock_batches_status_check;
  ALTER TABLE public.stock_batches
    ADD CONSTRAINT stock_batches_status_check
    CHECK (status IN ('disponible', 'quarantaine', 'perime', 'detruit'));
END;
$$;

