CREATE OR REPLACE FUNCTION public.app_receive_product_stock_with_batch(
  p_movement_id UUID,
  p_product_id TEXT,
  p_quantity INTEGER,
  p_reason TEXT,
  p_lot_number TEXT,
  p_performed_by_id TEXT,
  p_performed_by TEXT,
  p_performed_by_role TEXT,
  p_expiry_date DATE DEFAULT NULL,
  p_supplier_name TEXT DEFAULT NULL,
  p_supplier_reference TEXT DEFAULT NULL,
  p_purchase_price BIGINT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_result JSONB;
  v_product_name TEXT;
  v_existing public.stock_batches%ROWTYPE;
  v_created public.stock_batches%ROWTYPE;
BEGIN
  IF p_movement_id IS NULL
     OR NULLIF(trim(p_product_id), '') IS NULL
     OR p_quantity IS NULL OR p_quantity < 1 OR p_quantity > 1000000
     OR p_reason IS NULL OR length(trim(p_reason)) NOT BETWEEN 3 AND 500
     OR NULLIF(trim(p_performed_by_id), '') IS NULL
     OR NULLIF(trim(p_performed_by), '') IS NULL
     OR NULLIF(trim(p_performed_by_role), '') IS NULL
     OR (p_supplier_name IS NOT NULL AND length(trim(p_supplier_name)) > 160)
     OR (p_supplier_reference IS NOT NULL AND length(trim(p_supplier_reference)) > 160)
     OR (p_purchase_price IS NOT NULL AND p_purchase_price < 0) THEN
    RAISE EXCEPTION 'Données de réception de lot invalides.' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_existing FROM public.stock_batches WHERE id = p_movement_id::TEXT FOR UPDATE;
  IF FOUND THEN
    IF v_existing.product_id <> p_product_id
       OR v_existing.quantity_received <> p_quantity
       OR v_existing.lot_number IS DISTINCT FROM NULLIF(trim(p_lot_number), '')
       OR v_existing.expiry_date IS DISTINCT FROM p_expiry_date
       OR v_existing.supplier_name IS DISTINCT FROM NULLIF(trim(p_supplier_name), '')
       OR v_existing.supplier_reference IS DISTINCT FROM NULLIF(trim(p_supplier_reference), '')
       OR v_existing.purchase_price IS DISTINCT FROM p_purchase_price THEN
      RAISE EXCEPTION 'Cet identifiant de réception existe déjà avec d’autres données.' USING ERRCODE = '23505';
    END IF;
    v_result := public.app_receive_product_stock(
      p_movement_id, p_product_id, p_quantity, p_reason, p_lot_number,
      p_performed_by_id, p_performed_by, p_performed_by_role
    );
    RETURN v_result || jsonb_build_object('batch', to_jsonb(v_existing));
  END IF;

  v_result := public.app_receive_product_stock(
    p_movement_id, p_product_id, p_quantity, p_reason, p_lot_number,
    p_performed_by_id, p_performed_by, p_performed_by_role
  );
  SELECT name INTO v_product_name FROM public.products WHERE id = p_product_id;

  INSERT INTO public.stock_batches (
    id, product_id, product_name, receipt_movement_id, lot_number, expiry_date,
    quantity, quantity_received, quantity_remaining, purchase_price, supplier_name, supplier_reference,
    received_date, received_at, received_by_id, received_by, created_at
  ) VALUES (
    p_movement_id::TEXT, p_product_id, v_product_name, p_movement_id,
    NULLIF(trim(p_lot_number), ''), p_expiry_date, p_quantity, p_quantity, p_quantity,
    p_purchase_price, NULLIF(trim(p_supplier_name), ''), NULLIF(trim(p_supplier_reference), ''),
    CURRENT_DATE, now(), trim(p_performed_by_id), trim(p_performed_by), now()
  ) RETURNING * INTO v_created;

  RETURN v_result || jsonb_build_object('batch', to_jsonb(v_created));
END;
$$;

CREATE OR REPLACE FUNCTION public.app_track_stock_batch_issue_return()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_product_data JSONB;
  v_product_status TEXT;
  v_current NUMERIC;
  v_after_expiry INTEGER;
  v_expired_quantity INTEGER := 0;
  v_remaining_to_allocate INTEGER;
  v_allocated INTEGER;
  v_batch RECORD;
  v_source RECORD;
  v_already_returned INTEGER;
  v_source_remaining INTEGER;
  v_returned_for_batch INTEGER := 0;
  v_unavailable_return INTEGER := 0;
  v_return_quantity INTEGER;
BEGIN
  IF NEW.movement_type NOT IN ('sortie_commande', 'retour') THEN
    RETURN NEW;
  END IF;

  SELECT COALESCE(app_data, '{}'::JSONB), status
    INTO v_product_data, v_product_status
  FROM public.products
  WHERE id = NEW.product_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Produit introuvable pendant le suivi des lots.' USING ERRCODE = 'P0002';
  END IF;

  IF COALESCE(v_product_data->>'quantityAvailable', '') ~ '^-?[0-9]+$' THEN
    v_current := (v_product_data->>'quantityAvailable')::NUMERIC;
  ELSIF COALESCE(v_product_data->>'stockQuantity', '') ~ '^-?[0-9]+$' THEN
    v_current := (v_product_data->>'stockQuantity')::NUMERIC;
  ELSE
    v_current := 0;
  END IF;

  IF v_current < 0 OR v_current > 2147483647 OR v_current <> trunc(v_current) THEN
    RAISE EXCEPTION 'Quantité actuelle invalide pendant le suivi des lots.' USING ERRCODE = '22003';
  END IF;

  IF NEW.movement_type = 'sortie_commande' THEN
    -- Expired, tracked units are removed from the sellable aggregate stock in
    -- the same transaction as the attempted order. If stock becomes negative,
    -- the entire checkout rolls back instead of selling an expired lot.
    SELECT COALESCE(sum(quantity_remaining), 0)::INTEGER
      INTO v_expired_quantity
    FROM public.stock_batches
    WHERE product_id = NEW.product_id
      AND status = 'disponible'
      AND quantity_remaining IS NOT NULL
      AND quantity_remaining > 0
      AND expiry_date IS NOT NULL
      AND expiry_date < CURRENT_DATE;

    IF v_expired_quantity > v_current THEN
      RAISE EXCEPTION 'Stock incohérent : les lots suivis périmés dépassent le stock restant. Faites un inventaire par lot avant la vente.'
        USING ERRCODE = '23514';
    END IF;

    IF v_expired_quantity > 0 THEN
      UPDATE public.stock_batches
      SET status = 'perime',
          status_reason = 'Isolement automatique à la première vérification après la date de péremption.',
          status_updated_at = now(),
          status_updated_by_id = 'system',
          status_updated_by = 'Système'
      WHERE product_id = NEW.product_id
        AND status = 'disponible'
        AND quantity_remaining IS NOT NULL
        AND quantity_remaining > 0
        AND expiry_date IS NOT NULL
        AND expiry_date < CURRENT_DATE;

      v_after_expiry := v_current::INTEGER - v_expired_quantity;
      v_product_data := jsonb_set(v_product_data, '{quantityAvailable}', to_jsonb(v_after_expiry), TRUE);
      v_product_data := jsonb_set(v_product_data, '{stockQuantity}', to_jsonb(v_after_expiry), TRUE);
      UPDATE public.products
      SET app_data = v_product_data,
          status = CASE WHEN v_after_expiry = 0 THEN 'rupture' ELSE v_product_status END,
          updated_at = now()
      WHERE id = NEW.product_id;

      INSERT INTO public.stock_movements (
        id, product_id, product_name, movement_type, quantity,
        previous_quantity, new_quantity, reason, reference,
        performed_by_id, performed_by, performed_by_role
      ) VALUES (
        gen_random_uuid(), NEW.product_id, NEW.product_name, 'ajustement',
        v_expired_quantity, v_current::INTEGER, v_after_expiry,
        'Retrait automatique du stock vendable : lots périmés isolés.', NEW.reference,
        'system', 'Système', 'system'
      );
      v_current := v_after_expiry;
    END IF;

    v_remaining_to_allocate := NEW.quantity;
    FOR v_batch IN
      SELECT id, quantity_remaining
      FROM public.stock_batches
      WHERE product_id = NEW.product_id
        AND status = 'disponible'
        AND quantity_remaining > 0
        AND (expiry_date IS NULL OR expiry_date >= CURRENT_DATE)
      ORDER BY expiry_date ASC NULLS LAST, received_at ASC, id ASC
      FOR UPDATE
    LOOP
      EXIT WHEN v_remaining_to_allocate <= 0;
      v_allocated := LEAST(v_remaining_to_allocate, v_batch.quantity_remaining);

      UPDATE public.stock_batches
      SET quantity_remaining = quantity_remaining - v_allocated
      WHERE id = v_batch.id;

      INSERT INTO public.stock_batch_movements (
        stock_movement_id, batch_id, direction, quantity
      ) VALUES (NEW.id, v_batch.id, 'sortie', v_allocated);

      v_remaining_to_allocate := v_remaining_to_allocate - v_allocated;
    END LOOP;

    -- Any unallocated balance belongs to historic/untracked inventory. It
    -- remains in aggregate stock and is never assigned to a guessed lot.
    RETURN NEW;
  END IF;

  v_return_quantity := NEW.quantity;
  FOR v_source IN
    SELECT allocation.id AS allocation_id,
           allocation.batch_id,
           allocation.quantity AS allocated_quantity,
           batch.status AS batch_status,
           batch.expiry_date,
           batch.quantity_remaining
    FROM public.stock_batch_movements allocation
    JOIN public.stock_movements issued
      ON issued.id = allocation.stock_movement_id
    JOIN public.stock_batches batch
      ON batch.id = allocation.batch_id
    WHERE allocation.direction = 'sortie'
      AND issued.movement_type = 'sortie_commande'
      AND issued.reference = NEW.reference
      AND issued.product_id = NEW.product_id
    ORDER BY allocation.id
    FOR UPDATE OF batch
  LOOP
    EXIT WHEN v_return_quantity <= 0;
    SELECT COALESCE(sum(quantity), 0)::INTEGER
      INTO v_already_returned
    FROM public.stock_batch_movements
    WHERE direction = 'retour'
      AND source_allocation_id = v_source.allocation_id;

    v_source_remaining := GREATEST(0, v_source.allocated_quantity - v_already_returned);
    v_allocated := LEAST(v_return_quantity, v_source_remaining);
    IF v_allocated <= 0 THEN CONTINUE; END IF;

    IF v_source.batch_status = 'detruit' THEN
      RAISE EXCEPTION 'Le lot réservé a été détruit avant la restitution. Vérifiez le journal de stock.' USING ERRCODE = '23514';
    END IF;

    IF v_source.batch_status = 'disponible'
       AND v_source.expiry_date IS NOT NULL
       AND v_source.expiry_date < CURRENT_DATE THEN
      UPDATE public.stock_batches
      SET status = 'perime',
          status_reason = 'Isolement automatique lors du retour d’une commande.',
          status_updated_at = now(),
          status_updated_by_id = 'system',
          status_updated_by = 'Système'
      WHERE id = v_source.batch_id;
      v_source.batch_status := 'perime';
    END IF;

    UPDATE public.stock_batches
    SET quantity_remaining = COALESCE(quantity_remaining, 0) + v_allocated
    WHERE id = v_source.batch_id;

    INSERT INTO public.stock_batch_movements (
      stock_movement_id, batch_id, direction, quantity, source_allocation_id
    ) VALUES (
      NEW.id, v_source.batch_id, 'retour', v_allocated, v_source.allocation_id
    );

    IF v_source.batch_status <> 'disponible' THEN
      v_unavailable_return := v_unavailable_return + v_allocated;
    END IF;
    v_return_quantity := v_return_quantity - v_allocated;
  END LOOP;

  IF v_unavailable_return > 0 THEN
    IF v_unavailable_return > v_current THEN
      RAISE EXCEPTION 'La restitution dépasserait le stock disponible pendant le blocage du lot.' USING ERRCODE = '22003';
    END IF;
    v_after_expiry := v_current::INTEGER - v_unavailable_return;
    v_product_data := jsonb_set(v_product_data, '{quantityAvailable}', to_jsonb(v_after_expiry), TRUE);
    v_product_data := jsonb_set(v_product_data, '{stockQuantity}', to_jsonb(v_after_expiry), TRUE);
    UPDATE public.products
    SET app_data = v_product_data,
        status = CASE WHEN v_after_expiry = 0 THEN 'rupture' ELSE v_product_status END,
        updated_at = now()
    WHERE id = NEW.product_id;

    INSERT INTO public.stock_movements (
      id, product_id, product_name, movement_type, quantity,
      previous_quantity, new_quantity, reason, reference,
      performed_by_id, performed_by, performed_by_role
    ) VALUES (
      gen_random_uuid(), NEW.product_id, NEW.product_name, 'ajustement',
      v_unavailable_return, v_current::INTEGER, v_after_expiry,
      'Retour isolé : le lot est périmé ou en quarantaine et reste indisponible à la vente.', NEW.reference,
      NEW.performed_by_id, NEW.performed_by, NEW.performed_by_role
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_track_stock_batch_issue_return ON public.stock_movements;
CREATE TRIGGER trg_track_stock_batch_issue_return
AFTER INSERT ON public.stock_movements
FOR EACH ROW
WHEN (NEW.movement_type IN ('sortie_commande', 'retour'))
EXECUTE FUNCTION public.app_track_stock_batch_issue_return();

CREATE OR REPLACE FUNCTION public.app_set_stock_batch_status(
  p_batch_id UUID,
  p_target_status TEXT,
  p_reason TEXT,
  p_movement_id UUID,
  p_performed_by_id TEXT,
  p_performed_by TEXT,
  p_performed_by_role TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_product_id TEXT;
  v_product_name TEXT;
  v_product_data JSONB;
  v_product_status TEXT;
  v_current NUMERIC;
  v_new_quantity INTEGER;
  v_quantity_delta INTEGER := 0;
  v_batch public.stock_batches%ROWTYPE;
  v_existing public.stock_movements%ROWTYPE;
  v_has_active_reservation BOOLEAN := FALSE;
  v_movement_type TEXT := 'ajustement';
BEGIN
  IF p_batch_id IS NULL OR p_movement_id IS NULL
     OR p_target_status NOT IN ('disponible', 'quarantaine', 'detruit')
     OR p_reason IS NULL OR length(trim(p_reason)) NOT BETWEEN 3 AND 500
     OR NULLIF(trim(p_performed_by_id), '') IS NULL
     OR NULLIF(trim(p_performed_by), '') IS NULL
     OR NULLIF(trim(p_performed_by_role), '') IS NULL THEN
    RAISE EXCEPTION 'Données de changement d’état du lot invalides.' USING ERRCODE = '22023';
  END IF;

  SELECT product_id INTO v_product_id
  FROM public.stock_batches
  WHERE id = p_batch_id::TEXT;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Lot introuvable.' USING ERRCODE = 'P0002';
  END IF;

  SELECT name, COALESCE(app_data, '{}'::JSONB), status
    INTO v_product_name, v_product_data, v_product_status
  FROM public.products
  WHERE id = v_product_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Produit du lot introuvable.' USING ERRCODE = 'P0002';
  END IF;

  SELECT * INTO v_batch
  FROM public.stock_batches
  WHERE id = p_batch_id::TEXT
  FOR UPDATE;

  IF COALESCE(v_product_data->>'quantityAvailable', '') ~ '^-?[0-9]+$' THEN
    v_current := (v_product_data->>'quantityAvailable')::NUMERIC;
  ELSIF COALESCE(v_product_data->>'stockQuantity', '') ~ '^-?[0-9]+$' THEN
    v_current := (v_product_data->>'stockQuantity')::NUMERIC;
  ELSE
    v_current := 0;
  END IF;
  IF v_current < 0 OR v_current > 2147483647 OR v_current <> trunc(v_current) THEN
    RAISE EXCEPTION 'La quantité disponible du produit est invalide.' USING ERRCODE = '22003';
  END IF;
  v_new_quantity := v_current::INTEGER;

  SELECT * INTO v_existing
  FROM public.stock_movements
  WHERE id = p_movement_id;
  IF FOUND THEN
    IF v_existing.product_id <> v_product_id OR v_existing.movement_type <> 'ajustement' THEN
      RAISE EXCEPTION 'Cet identifiant de mouvement est déjà utilisé.' USING ERRCODE = '23505';
    END IF;
    RETURN jsonb_build_object('batch', to_jsonb(v_batch), 'quantityAvailable', v_new_quantity, 'movement', to_jsonb(v_existing));
  END IF;

  IF v_batch.status = p_target_status THEN
    RETURN jsonb_build_object('batch', to_jsonb(v_batch), 'quantityAvailable', v_new_quantity, 'movement', NULL);
  END IF;
  IF v_batch.status = 'detruit' THEN
    RAISE EXCEPTION 'Un lot détruit ne peut pas être réactivé.' USING ERRCODE = '22023';
  END IF;
  IF v_batch.quantity_remaining IS NULL THEN
    RAISE EXCEPTION 'Ce lot historique doit d’abord être rapproché par inventaire physique avant de changer son état.' USING ERRCODE = '23514';
  END IF;

  IF p_target_status = 'disponible' THEN
    IF v_batch.status <> 'quarantaine' THEN
      RAISE EXCEPTION 'Seul un lot en quarantaine peut être remis en disponibilité.' USING ERRCODE = '22023';
    END IF;
    IF v_batch.expiry_date IS NOT NULL AND v_batch.expiry_date < CURRENT_DATE THEN
      RAISE EXCEPTION 'Un lot périmé ne peut pas être remis en vente.' USING ERRCODE = '23514';
    END IF;
    v_quantity_delta := v_batch.quantity_remaining;
  ELSIF p_target_status IN ('quarantaine', 'detruit') AND v_batch.status = 'disponible'
        THEN
    v_quantity_delta := -v_batch.quantity_remaining;
  END IF;

  IF p_target_status IN ('quarantaine', 'detruit') THEN
    SELECT EXISTS (
      SELECT 1
      FROM public.stock_batch_movements allocation
      JOIN public.stock_movements issue ON issue.id = allocation.stock_movement_id
      JOIN public.orders order_row ON order_row.reference = issue.reference
      LEFT JOIN LATERAL (
        SELECT COALESCE(sum(returned.quantity), 0) AS quantity
        FROM public.stock_batch_movements returned
        WHERE returned.direction = 'retour'
          AND returned.source_allocation_id = allocation.id
      ) restored ON TRUE
      WHERE allocation.batch_id = p_batch_id::TEXT
        AND allocation.direction = 'sortie'
        AND order_row.status IN ('À confirmer', 'Confirmée', 'En préparation')
        AND COALESCE(order_row.app_data->>'stockReserved', 'false') = 'true'
        AND allocation.quantity > restored.quantity
    ) INTO v_has_active_reservation;
    IF v_has_active_reservation THEN
      RAISE EXCEPTION 'Ce lot a encore des unités réservées par une commande active. Traitez ou annulez ces commandes avant de le bloquer.' USING ERRCODE = '23514';
    END IF;
  END IF;

  IF v_current < 0 OR v_current > 2147483647 OR v_current <> trunc(v_current)
     OR v_current + v_quantity_delta < 0 OR v_current + v_quantity_delta > 2147483647 THEN
    RAISE EXCEPTION 'La quantité disponible ne permet pas ce changement d’état. Rapprochez le lot avec un inventaire.' USING ERRCODE = '22003';
  END IF;
  v_new_quantity := (v_current + v_quantity_delta)::INTEGER;

  IF p_target_status = 'detruit' THEN
    UPDATE public.stock_batches
    SET status = 'detruit',
        quantity_destroyed = quantity_destroyed + quantity_remaining,
        quantity_remaining = 0,
        status_reason = trim(p_reason),
        status_updated_at = now(),
        status_updated_by_id = trim(p_performed_by_id),
        status_updated_by = trim(p_performed_by)
    WHERE id = p_batch_id::TEXT
    RETURNING * INTO v_batch;
  ELSE
    UPDATE public.stock_batches
    SET status = p_target_status,
        status_reason = trim(p_reason),
        status_updated_at = now(),
        status_updated_by_id = trim(p_performed_by_id),
        status_updated_by = trim(p_performed_by)
    WHERE id = p_batch_id::TEXT
    RETURNING * INTO v_batch;
  END IF;

  IF v_quantity_delta <> 0 THEN
    v_product_data := jsonb_set(v_product_data, '{quantityAvailable}', to_jsonb(v_new_quantity), TRUE);
    v_product_data := jsonb_set(v_product_data, '{stockQuantity}', to_jsonb(v_new_quantity), TRUE);
    UPDATE public.products
    SET app_data = v_product_data,
        status = CASE WHEN v_new_quantity = 0 THEN 'rupture' WHEN p_target_status = 'disponible' THEN 'disponible' ELSE v_product_status END,
        updated_at = now()
    WHERE id = v_product_id;

    INSERT INTO public.stock_movements (
      id, product_id, product_name, movement_type, quantity,
      previous_quantity, new_quantity, reason, lot_number,
      performed_by_id, performed_by, performed_by_role
    ) VALUES (
      p_movement_id, v_product_id, v_product_name, 'ajustement', abs(v_quantity_delta),
      v_current::INTEGER, v_new_quantity, trim(p_reason), v_batch.lot_number,
      trim(p_performed_by_id), trim(p_performed_by), trim(p_performed_by_role)
    ) RETURNING * INTO v_existing;
  END IF;

  RETURN jsonb_build_object(
    'batch', to_jsonb(v_batch),
    'quantityAvailable', v_new_quantity,
    'movement', CASE WHEN v_existing.id IS NULL THEN NULL ELSE to_jsonb(v_existing) END
  );
END;
$$;

